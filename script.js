const root = document.documentElement;

/* ---------- Theme ---------- */
function applyTheme(t) { root.setAttribute("data-theme", t); try { localStorage.setItem("jo-theme", t); } catch (e) {} }
(function () {
  let s; try { s = localStorage.getItem("jo-theme"); } catch (e) {}
  if (!s) s = window.matchMedia && window.matchMedia("(prefers-color-scheme: light)").matches ? "light" : "dark";
  applyTheme(s);
})();
document.getElementById("themeToggle").addEventListener("click", () =>
  applyTheme(root.getAttribute("data-theme") === "dark" ? "light" : "dark"));

/* ---------- Language ---------- */
function applyLang(lang) {
  const d = I18N[lang] || I18N.es;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const v = d[el.getAttribute("data-i18n")];
    if (v == null) return;
    if (el.tagName === "META") el.setAttribute("content", v);
    else el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const v = d[el.getAttribute("data-i18n-html")];
    if (v != null) el.innerHTML = v;
  });
  root.setAttribute("lang", lang);
  document.querySelectorAll(".lang-opt").forEach((o) => o.classList.toggle("active", o.dataset.lang === lang));
  try { localStorage.setItem("jo-lang", lang); } catch (e) {}
}
(function () {
  let s; try { s = localStorage.getItem("jo-lang"); } catch (e) {}
  if (!s) s = (navigator.language || "es").toLowerCase().startsWith("en") ? "en" : "es";
  applyLang(s);
})();
document.getElementById("langToggle").addEventListener("click", () =>
  applyLang(root.getAttribute("lang") === "en" ? "es" : "en"));

/* ---------- Mobile menu ---------- */
const menuToggle = document.getElementById("menuToggle");
const navlinks = document.querySelector(".navlinks");
menuToggle.addEventListener("click", () => navlinks.classList.toggle("open"));
navlinks.querySelectorAll("a").forEach((a) => a.addEventListener("click", () => navlinks.classList.remove("open")));

/* ---------- Reveal on scroll ---------- */
const io = new IntersectionObserver((es) => {
  es.forEach((e) => { if (e.isIntersecting) { e.target.classList.add("in"); io.unobserve(e.target); } });
}, { threshold: 0.15 });
document.querySelectorAll(".reveal").forEach((el, i) => { el.style.transitionDelay = (i % 3 * 0.08) + "s"; io.observe(el); });

